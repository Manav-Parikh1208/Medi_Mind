# Modifiers to expand natural variations
time_modifiers = [
    "",
    " since morning",
    " for the past 2 days",
    " starting last night",
    " getting worse over the last week",
    " slightly improving with rest",
    " coming and going for three days",
    " continuously for past 24 hours",
    " since yesterday evening",
    " for over a week",
]

severity_modifiers = [
    "",
    " feeling very severe",
    " mild but persistent",
    " moderately painful",
    " causing great discomfort",
    " getting progressively worse",
    " accompanied by general weakness",
]

data = []

# Generate dataset rows (~50-80 rows per disease for 1000+ total rows)
for disease, templates in disease_symptoms.items():
    for template in templates:
        for _ in range(6):
            t_mod = random.choice(time_modifiers)
            s_mod = random.choice(severity_modifiers)
            concern = f"{template}{t_mod}{s_mod}".strip()
            data.append({"patient_concern": concern, "diagnosis": disease})

df = pd.DataFrame(data)
# Clean duplicates and shuffle
df = df.drop_duplicates(subset=["patient_concern"]).sample(frac=1.0, random_state=42).reset_index(drop=True)

print("Generated dataset shape:", df.shape)
print("Diagnosis counts:\n", df["diagnosis"].value_counts())

df.to_csv("patient_symptoms_textual.csv", index=False)
print("Updated patient_symptoms_textual.csv successfully!")
